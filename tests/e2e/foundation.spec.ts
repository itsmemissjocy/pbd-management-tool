import { test,expect } from '@playwright/test';
import ExcelJS from 'exceljs';
test('authentication, school setup, classes, subjects, student edit, import and tenant rejection',async({page,request})=>{
 test.setTimeout(60000);
 expect((await request.get('/api/data')).status()).toBe(401);
 await page.goto('/');
 await page.getByLabel('Kata laluan',{exact:true}).fill('wrong');
 await page.getByRole('button',{name:'Log masuk',exact:true}).click();
 await expect(page.getByRole('alert').filter({hasText:'tidak sah'})).toContainText('tidak sah');
 await page.getByLabel('Kata laluan',{exact:true}).fill('DemoGuru2026!');
 await page.getByRole('button',{name:'Log masuk',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Selamat mengajar, Cikgu.'})).toBeVisible();
 await page.getByRole('navigation').getByRole('button',{name:'Tetapan sekolah'}).click();
 await page.getByRole('button',{name:'Edit profil'}).click();
 await page.getByRole('dialog').getByLabel('Nama',{exact:true}).fill('Sekolah Ujian Sintetik');
 await page.getByRole('dialog').getByRole('button',{name:'Simpan',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Sekolah Ujian Sintetik'})).toBeVisible();
 await page.getByRole('navigation').getByRole('button',{name:'Kelas & tahun'}).click();
 await page.getByRole('button',{name:'Tambah kelas'}).click();
 const stamp=Date.now().toString();
 await page.getByRole('dialog').getByLabel('Nama',{exact:true}).fill(`1 Ujian ${stamp}`);
 await page.getByRole('dialog').getByRole('button',{name:'Simpan',exact:true}).click();
 await expect(page.getByRole('cell',{name:`1 Ujian ${stamp}`,exact:true})).toBeVisible();
 await page.getByRole('navigation').getByRole('button',{name:'Mata pelajaran'}).click();
 await page.getByRole('button',{name:'Tambah subjek'}).click();
 await page.getByRole('dialog').getByLabel('Nama',{exact:true}).fill(`Sains Ujian ${stamp}`);
 await page.getByRole('dialog').getByRole('button',{name:'Simpan',exact:true}).click();
 await page.getByRole('button',{name:'Tambah tugasan'}).click();
 await page.getByRole('dialog').getByRole('combobox',{name:'Mata pelajaran',exact:true}).selectOption({label:`Sains Ujian ${stamp}`});
 await page.getByRole('dialog').getByRole('button',{name:'Simpan',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('navigation').getByRole('button',{name:'Senarai murid'}).click();
 await page.getByRole('button',{name:'Tambah murid',exact:true}).click();
 await page.getByLabel('Nama penuh').fill('Murid Ujian Sintetik');
 await page.getByLabel('ID dalaman murid').fill(`TEST-${stamp}`);
 await page.getByRole('dialog').getByRole('button',{name:'Simpan',exact:true}).click();
 await page.getByLabel('Cari murid').fill(`TEST-${stamp}`);
 await page.getByRole('button',{name:'Edit',exact:true}).click();
 await page.getByLabel('Nama penuh').fill('Murid Dikemas Kini');
 await page.getByRole('dialog').getByRole('button',{name:'Simpan',exact:true}).click();
 await expect(page.getByText('Murid Dikemas Kini',{exact:true})).toBeVisible();
 const book=new ExcelJS.Workbook();book.addWorksheet('Murid').addRows([['ID','Nama'],[`IMPORT-${stamp}`,'Murid Import Sintetik']]);
 const bytes=await book.xlsx.writeBuffer();
 await page.getByRole('button',{name:'Import Excel',exact:true}).click();
 await page.locator('input[type=file]').setInputFiles({name:'students.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:Buffer.from(bytes)});
 await page.getByRole('button',{name:'Pratonton & sahkan'}).click();
 await expect(page.getByRole('cell',{name:'Murid Import Sintetik'})).toBeVisible();
 await page.getByRole('button',{name:'Sahkan import'}).click();
 await expect(page.getByRole('status').filter({hasText:'rekod berjaya ditambah'})).toBeVisible();
 await page.getByRole('button',{name:'Tutup',exact:true}).click();
 await page.getByLabel('Cari murid').fill(`IMPORT-${stamp}`);
 await expect(page.getByText('Murid Import Sintetik',{exact:true})).toBeVisible();
 // A forged cross-school class reference must be rejected server-side.
 const rejected=await page.evaluate(async()=>{const r=await fetch('/api/data',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({entity:'students',values:{name:'Cross Tenant',student_code:'BAD',class_id:'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'}})});return r.status;});
 expect(rejected).toBe(400);
 await page.getByRole('button',{name:'Edit',exact:true}).click();
 await page.getByRole('dialog').getByRole('combobox',{name:'Status',exact:true}).selectOption('archived');
 await page.getByRole('dialog').getByRole('button',{name:'Simpan',exact:true}).click();
 await expect(page.getByText('Tiada murid ditemui.',{exact:false})).toBeVisible();
 await page.getByLabel('Tapis status').selectOption('archived');
 await expect(page.getByText('Murid Import Sintetik',{exact:true})).toBeVisible();
 await page.getByRole('navigation').getByRole('button',{name:'Dashboard',exact:true}).click();
 await page.getByRole('button',{name:'Tukar bahasa',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Welcome back, Teacher.'})).toBeVisible();
 await expect(page.getByText('Total students',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Add student',exact:true}).click();
 await expect(page.getByRole('dialog').getByLabel('Full name',{exact:true})).toBeVisible();
 await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click();
 await page.getByRole('button',{name:'Change language',exact:true}).click();
 await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await expect(page.getByRole('heading',{name:'Selamat mengajar, Cikgu.'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/dashboard-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Buka navigasi'}).click();
 await page.getByRole('button',{name:'Log keluar',exact:true}).click();
 await expect(page.getByRole('button',{name:'Log masuk',exact:true})).toBeVisible();
});
